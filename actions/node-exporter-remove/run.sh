set -u
export DEBIAN_FRONTEND=noninteractive

# "Metrik izlemeyi kur"un (actions/node-exporter) tersi. Her adım bağımsızdır: biri başarısız olsa da
# diğerleri denenir; yalnız node_exporter hâlâ çalışıyorsa işlem başarısız sayılır.

# 1) node_exporter: servis durdurulur, paket ayarlarıyla (/etc/default/prometheus-node-exporter) silinir.
if dpkg -s prometheus-node-exporter >/dev/null 2>&1; then
    systemctl disable --now prometheus-node-exporter >/dev/null 2>&1 || true
    apt-get purge -y -q prometheus-node-exporter >/dev/null && echo "prometheus-node-exporter kaldırıldı."
else
    echo "prometheus-node-exporter zaten kurulu değil."
fi

# 2) Anakart sensör (Super I/O) sürücüleri: açılış dosyaları silinir, yüklü sürücüler çıkarılır.
for f in /etc/modules-load.d/ankamon-sensors.conf /etc/modules-load.d/tiha-mon-sensors.conf; do
    [ -e "$f" ] && rm -f "$f" && echo "$f silindi."
done
for mod in it87 nct6775 f71882fg; do
    lsmod | grep -q "^$mod " && modprobe -r "$mod" 2>/dev/null && echo "$mod sürücüsü bellekten çıkarıldı."
done

# 3) sensors-detect --auto'nun /etc/modules'a eklediği bölüm: "# Generated by sensors-detect" satırından
#    sonraki yorum/modül adı satırları (ilk boş satıra kadar). Dosyanın geri kalanına dokunulmaz.
if grep -q '^# Generated by sensors-detect' /etc/modules 2>/dev/null; then
    cp -p /etc/modules /etc/modules.ankamon-yedek
    awk '/^# Generated by sensors-detect/ {skip=1; next}
         skip && /^[[:space:]]*$/ {skip=0; next}
         skip && /^(#|[A-Za-z0-9_-]+[[:space:]]*$)/ {next}
         {skip=0; print}' /etc/modules.ankamon-yedek > /etc/modules
    echo "/etc/modules içindeki sensors-detect bölümü temizlendi (yedek: /etc/modules.ankamon-yedek)."
fi

# 4) lm-sensors: yalnız kendisi kaldırılacaksa (başka paket ona bağlı değilse) silinir.
if dpkg -s lm-sensors >/dev/null 2>&1; then
    others=$(apt-get -s purge lm-sensors 2>/dev/null | awk '/^Purg /{print $2}' | grep -vx 'lm-sensors' || true)
    if [ -z "$others" ]; then
        systemctl disable --now lm-sensors >/dev/null 2>&1 || true
        apt-get purge -y -q lm-sensors >/dev/null && echo "lm-sensors kaldırıldı."
    else
        echo "lm-sensors bırakıldı: kaldırılırsa şu paketler de giderdi: $(echo $others)."
    fi
fi


if systemctl is-active --quiet prometheus-node-exporter 2>/dev/null; then
    echo "HATA: prometheus-node-exporter hâlâ çalışıyor." >&2
    exit 1
fi
echo "Metrik izleme kaldırıldı; Ankamon bu tahtadan sensör verisi okumaz."
